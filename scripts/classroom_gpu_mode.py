#!/usr/bin/env python3
"""Switch classroom generation between the VM (normal) and a Tillicum GPU (classroom GPU mode).

    ./scripts/classroom_gpu_mode.sh start --course css360e-autumn-2026-c08m --admin-email you@uw.edu
    ./scripts/classroom_gpu_mode.sh status [--verify --admin-email you@uw.edu]
    ./scripts/classroom_gpu_mode.sh stop  --course css360e-autumn-2026-c08m --admin-email you@uw.edu [--cancel-job]

What a mode is: one JSON file the backend reads before every generation
(`backend/app/generation_mode.py`). In GPU mode all four conditions are
generated by the Tillicum service through an SSH tunnel on 127.0.0.1:9101;
retrieval, prompts, the queue, auth and the database stay on the VM. The VM
services keep running in GPU mode, so switching back is immediate.

`start` changes nothing until every check has passed, and puts the VM mode
back itself if a check after the switch fails:

  1. the backend is up, runs code that knows about modes, and is in VM mode;
  2. the course's activated version, from the backend's registry;
  3. the Tillicum serving session (recorded by start_finetuned_service.sh);
  4. the tunnel (UW Duo prompt, interactive, never stored);
  5. the GPU service: healthy, CUDA, enough time left, the course and version
     published, decoding identical to production;
  6. a direct probe: Base and course answers with the classroom cap, the same
     prompt token count the VM's Ollama computes for the same question;
  7. switch (one atomic file write), then the backend reports GPU mode;
  8. all four conditions through the backend, each proven to have been
     answered on the GPU (response model + the service's own counters).

`stop` switches back first (one file write), then proves the VM path: models
warmed, all four conditions answered on the VM. Then it closes the tunnel and
cancels the Tillicum job (`--cancel-job`) or reminds you it is still running.

Prompts: the admin password (or AISWE_VERIFY_PASSWORD) and UW Duo. Nothing is
stored. No answer text is printed.
"""

