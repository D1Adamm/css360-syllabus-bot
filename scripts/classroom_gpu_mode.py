def serving_session(run: Callable = subprocess.run) -> dict[str, Any]:
    """The session start_finetuned_service.sh recorded: node, port, job, expiry."""
    result = run(
        [sys.executable, str(REPO_ROOT / "training" / "serving_session.py"), "show", "--json"],
        capture_output=True, text=True,
    )
    if result.returncode != 0:
        raise Abort(
            "No serving session found. Start the GPU job on Tillicum first "
            "(./training/start_finetuned_service.sh), or pass --node/--remote-port. "
            + (result.stderr or "").strip()[:300]
        )
    try:
        session = json.loads(result.stdout)
    except ValueError as exc:
        raise Abort(f"serving_session.py returned invalid JSON: {exc}") from exc
    if not session.get("node"):
        raise Abort("The recorded serving session names no compute node.")
    return session


def activated_version(session: Any, course_id: str) -> str:
    """The version the backend serves this course from: online and ready, highest."""
    result = session.get(f"/api/db/courses/{course_id}/model")
    if not result.ok or not isinstance(result.body, dict):
        raise Abort(f"Could not read the model registry for {course_id} (HTTP {result.status}).")
    versions = result.body.get("versions") or {}
    online = sorted(
        (v for v, record in versions.items()
         if isinstance(record, dict) and record.get("deployment") == "online" and record.get("status") == "ready"),
        key=lambda v: int(v[1:]) if v[1:].isdigit() else 0,
    )
    if not online:
        raise Abort(f"{course_id} has no activated model version. Activate one in Admin -> Models first.")
    return online[-1]


def gpu_health_problems(health: dict[str, Any] | None, *, course_id: str, version: str, min_minutes: float) -> list[str]:
    if health is None:
        return ["the GPU service did not answer /health through the tunnel"]
    problems: list[str] = []
    if health.get("status") != "ok" or health.get("adapterLoaded") is not True:
        problems.append(f"status={health.get('status')!r} (base model not loaded yet?)")
    if health.get("cudaAvailable") is not True:
        problems.append("CUDA is not available on the node")
    if "base" not in (health.get("targets") or []):
        problems.append("this build cannot answer Base/RAG (no 'base' target): update the service on Tillicum")
    try:
        check_decoding(health.get("decoding"), expected_decoding(max_new_tokens=None))
    except HTTPException as exc:
        problems.append(str(exc.detail))
    remaining = health.get("secondsRemaining")
    if isinstance(remaining, (int, float)) and remaining < min_minutes * 60:
        problems.append(f"only {remaining / 60:.0f} min left on the allocation (need {min_minutes:.0f}; --min-minutes)")
    course = next((c for c in health.get("courses") or [] if c.get("courseId") == course_id), None)
    if course is None:
        problems.append(f"{course_id} is not published on Tillicum (promote_qlora_adapter.sh)")
    elif version not in (course.get("versions") or []):
        problems.append(f"{course_id} {version} is not published on Tillicum (published: {course.get('versions')})")
    return problems


def vm_prompt_tokens(transport: Any, ollama_url: str, model: str, question: str, timeout: float) -> int | None:
    """Prompt tokens the VM's Ollama computes for one user message (1 token generated)."""
    result = post_json(transport, f"{ollama_url}/api/chat", {
        "model": model, "messages": [{"role": "user", "content": question}], "stream": False,
        "options": {**classroom_options(), "num_predict": 1},
    }, timeout=timeout)
    if result.ok and isinstance(result.body, dict) and isinstance(result.body.get("prompt_eval_count"), int):
        return result.body["prompt_eval_count"]
    return None


def probe_gpu(transport: Any, cfg: Config, *, course_id: str, version: str, base_model: str) -> list[str]:
    """Direct Base and course answers on the GPU, held to the classroom settings."""
    problems: list[str] = []
    for target, body in (
        ("base", {"question": PROBE_QUESTION, "target": "base", "maxNewTokens": CLASSROOM_NUM_PREDICT}),
        ("course", {"question": PROBE_QUESTION, "courseId": course_id, "modelVersion": version,
                    "maxNewTokens": CLASSROOM_NUM_PREDICT}),
    ):
        result = post_json(transport, f"{cfg.gpu_url}/generate", body, timeout=cfg.timeout)
        data = result.body if isinstance(result.body, dict) else {}
        if not result.ok:
            problems.append(f"{target}: HTTP {result.status} {str(data.get('detail') or result.error or '')[:200]}")
            continue
        try:
            check_decoding(data.get("decoding"), expected_decoding(max_new_tokens=CLASSROOM_NUM_PREDICT))
        except HTTPException as exc:
            problems.append(f"{target}: {exc.detail}")
        if data.get("target") != target:
            problems.append(f"{target}: answered as target {data.get('target')!r}")
        if target == "course" and (data.get("courseId"), data.get("modelVersion")) != (course_id, version):
            problems.append(f"course: answered for {data.get('courseId')}@{data.get('modelVersion')}")
        timings = data.get("timings") or {}
        if int(timings.get("output_tokens") or 0) > CLASSROOM_NUM_PREDICT:
            problems.append(f"{target}: {timings.get('output_tokens')} output tokens > cap {CLASSROOM_NUM_PREDICT}")
        if not str(data.get("answer") or "").strip():
            problems.append(f"{target}: empty answer")
        say("INFO", f"GPU {target}: {timings.get('output_tokens', '?')} tokens in {data.get('generationSeconds', 0):.1f}s")
        if target == "base":
            vm_tokens = vm_prompt_tokens(transport, cfg.ollama_url, base_model, PROBE_QUESTION, cfg.timeout)
            gpu_tokens = timings.get("prompt_tokens")
            if vm_tokens is None:
                say("WARN", "could not ask the VM's Ollama for its prompt token count; tokenisation parity not checked")
            elif vm_tokens != gpu_tokens:
                problems.append(f"prompt tokens differ from the VM's Ollama ({gpu_tokens} vs {vm_tokens}): prompt format mismatch")
            else:
                say("PASS", f"prompt tokenised identically to the VM's Ollama ({vm_tokens} tokens)")
    return problems


def run_four(session: Any, course_id: str, timeout: float) -> dict[str, Any]:
    """The Compare page's four requests, sequentially, sharing one comparison id."""
    comparison = f"gpu-mode-{uuid.uuid4().hex[:12]}"
    out: dict[str, Any] = {}
    for condition in CONDITIONS:
        result = checks.generate(session, condition, course_id, question=PROBE_QUESTION, timeout=timeout,
                                 comparison_id=comparison)
        out[condition] = result
    return out


def four_condition_problems(results: dict[str, Any], *, on_gpu: bool, course_id: str, version: str) -> list[str]:
    problems: list[str] = []
    for condition, result in results.items():
        body = result.body if isinstance(result.body, dict) else {}
        if not result.ok:
            detail = body.get("detail")
            problems.append(f"{condition}: HTTP {result.status} {str(detail or result.error or '')[:200]}")
            continue
        model = str(body.get("model") or "")
        answered_on_gpu = GPU_MARK in model
        if answered_on_gpu != on_gpu:
            problems.append(f"{condition}: answered by {model!r}, expected {'the GPU' if on_gpu else 'the VM'}")
        if condition in ("fineTuned", "fineTunedRag") and body.get("modelVersion") != version:
            problems.append(f"{condition}: version {body.get('modelVersion')!r}, expected {version}")
        if on_gpu and condition in ("fineTuned", "fineTunedRag") and f"{course_id}@{version}" not in model:
            problems.append(f"{condition}: not answered by {course_id}@{version} ({model!r})")
        say("INFO", f"{condition:12} {result.seconds:5.1f}s  {len(str(body.get('answer') or ''))} chars  {model}")
    return problems


def backend_mode(session: Any) -> dict[str, Any]:
    result = session.get("/api/admin/generation-mode")
    if not result.ok or not isinstance(result.body, dict):
        raise Abort(
            f"GET /api/admin/generation-mode failed (HTTP {result.status}). Is the backend running code that "
            "includes classroom GPU mode? (git pull, then systemctl --user restart aiswe-backend)"
        )
    return result.body


def sign_in(cfg: Config, email: str | None, transport: Any, *, no_auth: bool = False) -> Any:
    if no_auth:
        # scripts/classroom_load_harness.py only: it answers as an administrator.
        return checks.BackendSession(cfg.backend_url, transport, timeout=cfg.timeout)
    credentials = checks.resolve_admin_credentials(email)
    if credentials is None:
        raise Abort("An administrator sign-in is needed: --admin-email and the password (prompt or AISWE_VERIFY_PASSWORD).")
    session = checks.BackendSession(cfg.backend_url, transport, timeout=cfg.timeout)
    login = session.login(*credentials)
    if not login.ok or not session.signed_in:
        raise Abort(f"Sign-in failed (HTTP {login.status}).")
    return session


def vm_model_names(course_id: str, version: str) -> tuple[str, str | None, str]:
    """(base model, the course's VM Ollama tag, the fine-tuned service's Ollama URL)."""
    base = (os.environ.get("OLLAMA_MODEL") or "llama3.2:3b").strip()
    try:
        values = local_helpers.parse_env_file(FINETUNED_ENV.read_text(encoding="utf-8"))
    except OSError:
        values = {}
    try:
        mapping = service_helpers.parse_model_map(values.get(service_helpers.MODEL_MAP_ENV))
    except service_helpers.CourseAdapterError:
        mapping = {}
    tag = mapping.get(course_id, {}).get(version)
    return base, tag, (values.get("OLLAMA_BASE_URL") or "http://127.0.0.1:11434").rstrip("/")


