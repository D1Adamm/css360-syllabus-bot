def ssh_base(cfg: Config) -> list[str]:
    return ["ssh", "-o", f"ControlPath={cfg.control_path}"]


def tunnel_alive(cfg: Config, run: Callable = subprocess.run) -> bool:
    if not cfg.control_path.exists():
        return False
    result = run(ssh_base(cfg) + ["-O", "check", cfg.tillicum_login], capture_output=True, text=True)
    return result.returncode == 0


def read_tunnel_state(cfg: Config) -> dict[str, Any]:
    try:
        data = json.loads(cfg.tunnel_state.read_text(encoding="utf-8"))
        return data if isinstance(data, dict) else {}
    except (OSError, ValueError):
        return {}


def open_tunnel(cfg: Config, node: str, remote_port: int, run: Callable = subprocess.run) -> None:
    STATE_ROOT.mkdir(parents=True, exist_ok=True)
    print(f"      Opening the tunnel 127.0.0.1:{cfg.gpu_port} -> {node}:{remote_port} via {cfg.tillicum_login}.")
    print("      Complete UW password / Duo if prompted.", flush=True)
    result = run(
        ["ssh", "-f", "-N",
         "-o", "ControlMaster=yes", "-o", f"ControlPath={cfg.control_path}", "-o", "ControlPersist=yes",
         "-o", "ExitOnForwardFailure=yes", "-o", "ServerAliveInterval=30", "-o", "ServerAliveCountMax=3",
         "-L", f"127.0.0.1:{cfg.gpu_port}:{node}:{remote_port}", cfg.tillicum_login],
    )
    if result.returncode != 0:
        raise Abort("SSH tunnel failed (authentication cancelled, network, or the port forward was refused).")
    cfg.tunnel_state.write_text(
        json.dumps({"node": node, "remotePort": remote_port, "localPort": cfg.gpu_port,
                    "login": cfg.tillicum_login, "openedAt": now_iso()}) + "\n",
        encoding="utf-8",
    )


def close_tunnel(cfg: Config, run: Callable = subprocess.run) -> bool:
    closed = False
    if cfg.control_path.exists():
        result = run(ssh_base(cfg) + ["-O", "exit", cfg.tillicum_login], capture_output=True, text=True)
        closed = result.returncode == 0
    cfg.control_path.unlink(missing_ok=True)
    cfg.tunnel_state.unlink(missing_ok=True)
    return closed


def cancel_job(cfg: Config, job_id: str, run: Callable = subprocess.run) -> bool:
    """`scancel` through the tunnel's already-authenticated connection."""
    if not job_id.isdigit():
        return False
    result = run(ssh_base(cfg) + [cfg.tillicum_login, "scancel", job_id], capture_output=True, text=True)
    return result.returncode == 0


