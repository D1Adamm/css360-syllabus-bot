def cmd_start(args: argparse.Namespace, cfg: Config, transport: Any) -> int:
    print("Classroom GPU mode: start. Nothing changes until every check below passes.\n")
    if not get_json(transport, f"{cfg.backend_url}/api/health"):
        raise Abort(f"The backend at {cfg.backend_url} is not answering /api/health.")
    session = sign_in(cfg, args.admin_email, transport, no_auth=args.no_auth)
    try:
        mode = backend_mode(session)
        if mode.get("mode") == gm.GPU:
            raise Abort("The backend is already in GPU mode. Use `status`, or `stop` first.")
        if mode.get("error"):
            raise Abort(f"The current mode file is unreadable ({mode['error']}); fix or remove it first.")
        say("PASS", "backend up, in VM mode")

        version = args.version or activated_version(session, args.course)
        say("PASS", f"{args.course}: version {version}" + (" (--version)" if args.version else " (activated in the backend)"))

        if args.node:
            node, remote_port, job_id, expires = args.node, args.remote_port, args.job_id or "", ""
        else:
            info = serving_session()
            node, remote_port = str(info["node"]), int(info.get("port") or DEFAULT_REMOTE_PORT)
            job_id, expires = str(info.get("jobId") or ""), str(info.get("expiresAt") or "")
        node = local_helpers_validate_node(node)
        say("PASS", f"Tillicum session: job {job_id or '?'} on {node}:{remote_port}, ends {expires or 'unknown'}")

        opened = False
        state = read_tunnel_state(cfg)
        if args.no_tunnel:
            if not get_json(transport, f"{cfg.gpu_url}/health"):
                raise Abort(f"--no-tunnel, but nothing answers {cfg.gpu_url}/health")
            say("PASS", f"using the existing forward on {cfg.gpu_url} (--no-tunnel)")
        elif tunnel_alive(cfg) and state.get("node") == node and get_json(transport, f"{cfg.gpu_url}/health"):
            say("PASS", f"reusing the open tunnel to {node}")
        else:
            close_tunnel(cfg)
            open_tunnel(cfg, node, remote_port)
            opened = True
            say("PASS", f"tunnel open: {cfg.gpu_url} -> {node}:{remote_port}")

        try:
            health = get_json(transport, f"{cfg.gpu_url}/health", timeout=15)
            problems = gpu_health_problems(health, course_id=args.course, version=version, min_minutes=args.min_minutes)
            if problems:
                raise Abort("GPU service not ready: " + "; ".join(problems))
            say("PASS", f"GPU service healthy on {health.get('gpuName') or 'GPU'}; decoding = production; "
                        f"{(health.get('secondsRemaining') or 0) / 60:.0f} min left")

            base_model, _, _ = vm_model_names(args.course, version)
            problems = probe_gpu(transport, cfg, course_id=args.course, version=version, base_model=base_model)
            if problems:
                raise Abort("GPU probe failed: " + "; ".join(problems))
            say("PASS", "direct GPU probe: Base and course answers within the classroom cap")

            before = (get_json(transport, f"{cfg.gpu_url}/health") or {}).get("served") or {}
            previous = read_mode_file()[1]
            path = write_mode_file({
                "mode": gm.GPU, "gpuUrl": cfg.gpu_url, "since": now_iso(), "node": node, "jobId": job_id,
                "expiresAt": expires, "courseId": args.course, "modelVersion": version,
                "switchedBy": os.environ.get("USER", ""),
            })
            try:
                mode = backend_mode(session)
                if mode.get("mode") != gm.GPU:
                    raise Abort(f"wrote {path} but the backend reports mode {mode.get('mode')!r} ({mode.get('error')})")
                say("PASS", f"switched: backend now generating on the GPU ({path})")

                problems = four_condition_problems(run_four(session, args.course, cfg.timeout),
                                                   on_gpu=True, course_id=args.course, version=version)
                after = (get_json(transport, f"{cfg.gpu_url}/health") or {}).get("served") or {}
                served = {k: int(after.get(k, 0)) - int(before.get(k, 0)) for k in ("base", "course")}
                if served["base"] < 2 or served["course"] < 2:
                    problems.append(f"the GPU served base +{served['base']}, course +{served['course']} (expected +2 each)")
                if problems:
                    raise Abort("four-condition check in GPU mode failed: " + "; ".join(problems))
                say("PASS", f"all four conditions answered on the GPU (GPU counters: base +{served['base']}, course +{served['course']})")
            except BaseException:
                write_mode_file(previous if previous is not None else {"mode": gm.VM})
                say("FAIL", "restored the previous mode (VM); the backend is generating on the VM again")
                raise
        except BaseException:
            if opened:
                close_tunnel(cfg)
                say("INFO", "closed the tunnel this run opened")
            raise
    finally:
        session.logout()

    print()
    print("CLASSROOM GPU MODE ACTIVE: Base, RAG, Fine-Tuned and Fine-Tuned + RAG are generated on the Tillicum GPU.")
    print(f"  Job {job_id or '?'} on {node} ends {expires or 'at the end of its allocation'}; GPU mode stops working then.")
    print("  Check:   ./scripts/classroom_gpu_mode.sh status")
    print(f"  Revert:  ./scripts/classroom_gpu_mode.sh stop --course {args.course} --admin-email <you> [--cancel-job]")
    return 0


def local_helpers_validate_node(node: str) -> str:
    deploy = _load("finetuned_deploy_helpers", LIB / "finetuned_deploy_helpers.py")
    try:
        return deploy.validate_compute_hostname(node)
    except ValueError as exc:
        raise Abort(f"Invalid compute node hostname {node!r}: {exc}") from exc


def cmd_stop(args: argparse.Namespace, cfg: Config, transport: Any) -> int:
    print("Classroom GPU mode: stop. Switching back to the VM first, then proving it.\n")
    _, _, before = read_mode_file()
    details = before.details if isinstance(before, gm.GenerationMode) else {}
    job_id = str(args.job_id or details.get("jobId") or "")
    write_mode_file({"mode": gm.VM, "since": now_iso(), "switchedBy": os.environ.get("USER", "")})
    say("PASS", "mode file: vm (new requests generate on the VM from now)")

    failures: list[str] = []
    session = sign_in(cfg, args.admin_email, transport, no_auth=args.no_auth)
    try:
        mode = backend_mode(session)
        if mode.get("mode") != gm.VM:
            failures.append(f"backend reports mode {mode.get('mode')!r}")
        else:
            say("PASS", "backend reports VM mode")

        version = args.version or activated_version(session, args.course)
        base_model, tag, ft_ollama = vm_model_names(args.course, version)
        if tag is None:
            failures.append(f"{args.course} {version} is not mapped in {FINETUNED_ENV}")
        else:
            warm = _load("warm_classroom_models", REPO_ROOT / "scripts" / "warm_classroom_models.py")
            print("      Warming the VM models (they may have been unloaded while the GPU served):", flush=True)
            if warm.main(["--base-ollama", cfg.ollama_url, "--base-model", base_model,
                          "--finetuned-ollama", ft_ollama, "--finetuned-model", tag, "--keep-alive", args.keep_alive]) != 0:
                failures.append("warming the VM models failed")
            else:
                say("PASS", "VM models resident")

        ft_health = get_json(transport, f"{cfg.finetuned_url}/health")
        if not ft_health or ft_health.get("status") != "ok":
            failures.append(f"VM fine-tuned service {cfg.finetuned_url} is not healthy")
        problems = four_condition_problems(run_four(session, args.course, cfg.timeout),
                                           on_gpu=False, course_id=args.course, version=version)
        failures += problems
        if not problems:
            say("PASS", "all four conditions answered on the VM")
    finally:
        session.logout()

    if args.cancel_job and job_id and tunnel_alive(cfg):
        if cancel_job(cfg, job_id):
            say("PASS", f"cancelled Tillicum job {job_id}")
            job_id = ""
        else:
            say("WARN", f"could not cancel Tillicum job {job_id}; cancel it by hand")
    closed = close_tunnel(cfg)
    say("PASS" if closed else "INFO", "tunnel closed" if closed else "no tunnel was open")

    print()
    if failures:
        print("VM MODE IS ACTIVE, BUT SOME CHECKS FAILED:")
        for failure in failures:
            print(f"  - {failure}")
    else:
        print("VM MODE ACTIVE: all four conditions are generated on this VM, and verified.")
    if job_id:
        print(f"  REMINDER: Tillicum job {job_id} is still running and using GPU time. On Tillicum: scancel {shlex.quote(job_id)}")
    return 1 if failures else 0


def cmd_status(args: argparse.Namespace, cfg: Config, transport: Any) -> int:
    path, text, mode = read_mode_file()
    print(f"Mode file: {path}" + ("" if text is not None else " (absent: VM mode)"))
    if isinstance(mode, str):
        print(f"MODE: VM (the file is {mode}; the backend ignores it)")
        mode = gm.VM_MODE
    print(f"MODE: {'CLASSROOM GPU' if mode.is_gpu else 'VM (normal)'}")
    for key, value in (mode.details or {}).items():
        print(f"  {key}: {value}")

    alive = tunnel_alive(cfg)
    state = read_tunnel_state(cfg)
    health = get_json(transport, f"{cfg.gpu_url}/health") if alive or mode.is_gpu else None
    print(f"\nTunnel: {'open to ' + str(state.get('node')) if alive else 'closed'} ({cfg.gpu_url})")
    if health:
        remaining = health.get("secondsRemaining")
        print(f"  GPU service: {health.get('status')} on {health.get('gpuName') or '?'}, "
              f"{'%.0f min left' % (remaining / 60) if isinstance(remaining, (int, float)) else 'time left unknown'}, "
              f"adapters {health.get('loadedAdapters')}, served {health.get('served')}")

    base_model, _, ft_ollama = vm_model_names(mode.details.get("courseId", ""), mode.details.get("modelVersion", ""))
    rows = gm.describe(mode, ollama_url=cfg.ollama_url, ollama_model=base_model, finetuned_url=cfg.finetuned_url)["routes"]
    print("\nWhere each condition is generated:")
    for condition in CONDITIONS:
        print(f"  {condition:13} {rows[condition]}")

    print("\nVM services (ready for VM mode):")
    print(f"  backend      {'ok' if get_json(transport, cfg.backend_url + '/api/health') else 'DOWN'} ({cfg.backend_url})")
    ft = get_json(transport, cfg.finetuned_url + "/health")
    print(f"  fine-tuned   {(ft or {}).get('status', 'DOWN')} ({cfg.finetuned_url} -> {(ft or {}).get('ollamaUrl', '?')})")
    for url in dict.fromkeys([cfg.ollama_url, ft_ollama]):
        ps = get_json(transport, url + "/api/ps")
        names = [m.get("name") for m in (ps or {}).get("models") or []]
        print(f"  ollama       {url}: {'resident ' + ', '.join(names) if names else ('nothing resident' if ps is not None else 'DOWN')}")

    problems = []
    if mode.is_gpu and not health:
        problems.append("GPU MODE IS ON BUT THE GPU SERVICE IS UNREACHABLE: students get errors. Run: ./scripts/classroom_gpu_mode.sh stop ...")
    if mode.is_gpu and health and isinstance(health.get("secondsRemaining"), (int, float)) and health["secondsRemaining"] < 900:
        problems.append("the GPU allocation ends within 15 minutes: plan to run `stop`")
    if not mode.is_gpu and alive:
        problems.append("VM mode, but the GPU tunnel is still open (and the Tillicum job may still be running)")

    if args.verify:
        session = sign_in(cfg, args.admin_email, transport, no_auth=args.no_auth)
        try:
            seen = backend_mode(session)
        finally:
            session.logout()
        agree = seen.get("mode") == mode.kind
        print(f"\nBackend reports: {seen.get('mode')} {'(agrees with the file)' if agree else '(DISAGREES with the file)'}")
        if not agree:
            problems.append("the backend and the mode file disagree")

    for problem in problems:
        print(f"\nWARNING: {problem}")
    return 1 if problems else 0


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="command", required=True)
    for name in ("start", "stop", "status"):
        p = sub.add_parser(name)
        p.add_argument("--admin-email", help=f"Administrator sign-in (password from ${checks.PASSWORD_ENV} or a prompt).")
        p.add_argument("--backend-url", default=checks.DEFAULT_BACKEND_URL)
        p.add_argument("--gpu-port", type=int, default=int(os.environ.get("GPU_MODE_LOCAL_PORT") or DEFAULT_GPU_PORT))
        p.add_argument("--timeout", type=float, default=180.0)
        p.add_argument("--no-auth", action="store_true", help=argparse.SUPPRESS)
        if name in ("start", "stop"):
            p.add_argument("--course", required=True, help="The course being taught, e.g. css360e-autumn-2026-c08m.")
            p.add_argument("--version", help="Override the activated version (default: read from the backend).")
        if name == "start":
            p.add_argument("--node", help="Compute node, instead of the recorded serving session.")
            p.add_argument("--remote-port", type=int, default=DEFAULT_REMOTE_PORT)
            p.add_argument("--job-id", help="Slurm job id, with --node.")
            p.add_argument("--no-tunnel", action="store_true",
                           help="Use a forward already open on --gpu-port (opened by hand) instead of opening one.")
            p.add_argument("--min-minutes", type=float, default=DEFAULT_MIN_MINUTES,
                           help="Refuse a session with less time left than this (default %(default)s).")
        if name == "stop":
            p.add_argument("--cancel-job", action="store_true", help="scancel the Tillicum job through the open tunnel.")
            p.add_argument("--job-id", help="The Slurm job to cancel (default: the one GPU mode recorded).")
            p.add_argument("--keep-alive", default="4h", help="keep_alive for the warmed VM models (default %(default)s).")
        if name == "status":
            p.add_argument("--verify", action="store_true", help="Also ask the backend (needs --admin-email).")
    return parser


def main(argv: list[str] | None = None, *, transport: Any = None) -> int:
    args = build_parser().parse_args(argv)
    cfg = Config(backend_url=args.backend_url.rstrip("/"), gpu_port=args.gpu_port, timeout=args.timeout)
    transport = transport or checks.Transport()
    command = {"start": cmd_start, "stop": cmd_stop, "status": cmd_status}[args.command]
    try:
        return command(args, cfg, transport)
    except Abort as exc:
        print(f"\nFAIL  {exc}", file=sys.stderr)
        if args.command == "start":
            print("The backend is in VM mode; nothing was left half-switched.", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
